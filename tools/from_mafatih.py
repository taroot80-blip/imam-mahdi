import re,json
raw=open('research/src/mafatih.txt',encoding='utf8').read()
pages={}
for m in re.finditer(r'#(\d+)\n(.*?)(?=\n#\d+\n|\Z)',raw,re.S): pages[int(m[1])]=m[2].strip()
FN=re.compile(r'\s*\([٠-٩]+\)')
def clean(t):
    t=FN.sub('',t).replace('صلى‌الله‌عليه‌وآله','صلى الله عليه وآله').replace('عليه‌السلام','عليه السلام').replace('عليهم‌السلام','عليهم السلام').replace('عليها‌السلام','عليها السلام')
    return re.sub(r' +',' ',t).replace(' ،','،').replace(' ؛','؛').replace(' :',':').strip()
D=re.compile(r'[\u064B-\u0652\u0670\u200c\u200d\s]')
def strip(x):
    out=[];mp=[]
    for i,c in enumerate(x):
        if not D.match(c): out.append(c);mp.append(i)
    return ''.join(out),mp
def seg(pfrom,pto,start,end,inc_end=True):
    s=' '.join(pages[p] for p in range(pfrom,pto+1))
    S,mp=strip(s);a,_=strip(start);b,_=strip(end)
    i=S.index(a); j=S.index(b,i)
    return clean(s[mp[i]:(mp[j+len(b)-1]+1 if inc_end else mp[j])])
def paras(t,n=75):
    out=[];cur=[]
    for w in t.split():
        cur.append(w)
        if len(cur)>=n and re.search(r'[،.؟!؛]$',w): out.append(' '.join(cur));cur=[]
    if cur: out.append(' '.join(cur))
    return '\n\n'.join(out)
